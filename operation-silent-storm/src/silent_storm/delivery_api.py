from .review_api import _body, _page_args, _version
from .storage import canonical_json
from .ui.citation import citation_page


def reopen_snapshot(briefs, candidate: dict) -> dict:
    """Reopen a frozen export in its original workspace without importing decisions."""
    if not isinstance(candidate, dict) or not isinstance(candidate.get("brief_id"), str):
        raise ValueError("Choose a saved Traced specialist brief JSON file.")
    if len(canonical_json(candidate).encode("utf-8")) > 2 * 1024 * 1024:
        raise ValueError("Saved snapshot JSON exceeds the 2 MiB reopen limit.")
    saved = briefs.get_brief(candidate["brief_id"])
    if canonical_json(candidate) != canonical_json(saved):
        raise ValueError("The JSON does not match the immutable saved snapshot in this workspace.")
    return briefs.validate_brief(saved["brief_id"])


def register_delivery_routes(server: Flask, store, briefs, diffs, exporter) -> None:
    @server.get("/api/release-diff")
    def release_diff():
        return jsonify(
            diffs.compare(
                request.args.get("baseline", ""),
                request.args.get("current", ""),
                category=request.args.get("category", "all"),
                **_page_args(),
            )
        )

    @server.post("/api/scenarios/<scenario_id>/brief-preview")
    def brief_preview(scenario_id: str):
        body = _body({"review_ids"})
        return jsonify(briefs.preview(scenario_id, body.get("review_ids", [])))

    @server.route("/api/scenarios/<scenario_id>/briefs", methods=["GET", "POST"])
    def scenario_briefs(scenario_id: str):
        if request.method == "GET":
            return jsonify(briefs.list_briefs(scenario_id, **_page_args()))
        body = _body({"title", "reviewer", "review_versions", "expected_version", "source_origin"})
        return jsonify(
            briefs.create(
                scenario_id,
                title=body.get("title", ""),
                reviewer=body.get("reviewer", ""),
                review_versions=body.get("review_versions", {}),
                expected_version=_version(body.get("expected_version"), "expected_version"),
                source_origin=body.get("source_origin", "unspecified"),
            )
        ), 201

    @server.get("/api/briefs/<brief_id>")
    def brief_detail(brief_id: str):
        return jsonify(briefs.get_brief(brief_id))

    @server.get("/api/briefs/<brief_id>/validation")
    def brief_validation(brief_id: str):
        return jsonify(briefs.validate_brief(brief_id))

    @server.post("/api/briefs/reopen")
    def brief_reopen():
        body = _body({"snapshot"})
        return jsonify(reopen_snapshot(briefs, body.get("snapshot")))

    @server.get("/api/briefs/<brief_id>/export.<format_name>")
    def brief_export(brief_id: str, format_name: str):
        snapshot = briefs.get_brief(brief_id)
        # IDs are generated by the brief service, never taken as filesystem paths.
        if format_name == "md":
            markdown = briefs.markdown(brief_id)
            # Downloads open outside the app as well; retain the frozen selector
            # while making its workspace-relative URL usable in a Markdown reader.
            for citation in snapshot["citations"]:
                relative = citation["href"]
                markdown = markdown.replace(
                    "](" + relative + ")", "](" + request.host_url.rstrip("/") + relative + ")"
                )
            data, mime = markdown.encode("utf-8"), "text/markdown"
        elif format_name == "json":
            data = json.dumps(snapshot, ensure_ascii=False, sort_keys=True, indent=2).encode(
                "utf-8"
            )
            mime = "application/json"
        elif format_name == "zip":
            data, mime = exporter.package(brief_id), "application/zip"
        else:
            abort(404, description="Choose Markdown, snapshot JSON or a portable case ZIP.")
        response = send_file(
            io.BytesIO(data),
            mimetype=mime,
            as_attachment=True,
            download_name=f"{snapshot['brief_id']}.{format_name}",
            max_age=0,
        )
        response.headers["Cache-Control"] = "no-store"
        return response

    @server.get("/api/briefs/<brief_id>/bundle.json")
    def brief_bundle(brief_id: str):
        response = jsonify(exporter.bundle(brief_id).model_dump(mode="json"))
        response.headers["Cache-Control"] = "no-store"
        return response

    def evidence_response(release_id: str, frame_id: str):
        release = store.get_release(release_id) if release_id else None
        frame = store.get_frame(release_id, frame_id) if release and frame_id else None
        if frame is None:
            raise ReviewNotFoundError("The exact cited frame is unavailable in this workspace.")
        expected = request.args.get("sha256")
        if expected is not None:
            if re.fullmatch(r"[0-9a-f]{64}", expected) is None:
                raise ValueError("The saved citation checksum is invalid.")
            frame["citation_expected_sha256"] = expected
            try:
                path = resolve_frame_path(release["dataset_root"], frame["relative_path"])
                if path.stat().st_size > 20 * 1024 * 1024:
                    raise ValueError("The image exceeds the selected citation verification limit.")
                frame["citation_hash_matches"] = sha256_file(path) == expected
            except (OSError, ValueError):
                frame["citation_hash_matches"] = False
            frame["hash_verification"] = (
                "citation_byte_match"
                if frame["citation_hash_matches"]
                else "citation_byte_mismatch"
            )
            if not frame["citation_hash_matches"]:
                frame["media_available"] = False
                frame["media_availability_error"] = (
                    "Current image bytes do not verify against the saved citation."
                )
        response = Response(
            citation_page(frame, release, reveal=request.args.get("reveal") == "1"),
            mimetype="text/html",
        )
        response.headers["Cache-Control"] = "no-store"
        response.headers["Content-Security-Policy"] = (
            "default-src 'none'; style-src 'self' 'unsafe-inline'; img-src 'self'; "
            "font-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'self'"
        )
        return response

    @server.get("/evidence")
    def exact_evidence():
        return evidence_response(
            request.args.get("release_id", ""), request.args.get("frame_id", "")
        )

    @server.get("/evidence/<release_id>/<path:frame_id>")
    def exact_evidence_path(release_id: str, frame_id: str):
        return evidence_response(release_id, frame_id)

    @server.get("/evidence-media")
    def exact_evidence_bytes():
        """Serve the very bytes verified against a frozen citation, not a later path read."""
        expected = request.args.get("sha256", "")
        if re.fullmatch(r"[0-9a-f]{64}", expected) is None:
            raise ValueError("The saved citation checksum is invalid.")
        rid, fid = request.args.get("release_id", ""), request.args.get("frame_id", "")
        release = store.get_release(rid) if rid else None
        frame = store.get_frame(rid, fid) if release and fid else None
        if frame is None:
            raise ReviewNotFoundError("The cited image is unavailable.")
        try:
            path = resolve_frame_path(release["dataset_root"], frame["relative_path"])
            if path.stat().st_size > 20 * 1024 * 1024:
                raise ValueError("Selected image exceeds the verification limit.")
            with path.open("rb") as stream:
                content = stream.read(20 * 1024 * 1024 + 1)
        except (OSError, ValueError) as exc:
            raise ReviewNotFoundError("The cited image is unavailable.") from exc
        if len(content) > 20 * 1024 * 1024 or hashlib.sha256(content).hexdigest() != expected:
            raise ReviewNotFoundError("Current image bytes do not match the saved citation.")
        mime = {
            ".jpg": "image/jpeg",
            ".jpeg": "image/jpeg",
            ".png": "image/png",
            ".webp": "image/webp",
        }[path.suffix.lower()]
        response = Response(content, mimetype=mime)
        response.headers["Cache-Control"] = "no-store"
        return response
